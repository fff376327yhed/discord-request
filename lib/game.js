export function stepView(user, { page = 0, full = false } = {}) {
  if (user.dead || user.stage >= STEPS.length) {
    return endingView(user, page, full);
  }
  if (user.nextAt && user.nextAt > Date.now()) {
    return waitingView(user);
  }

  const step = STEPS[user.stage];

  // 마지막 쪽에서 나올 진짜 버튼
  // freeText 가 있으면 "✍️ 직접 입력" 버튼을 같이 붙인다. 한 줄(최대 5개)에 다 안 들어가면 둘째 줄로 내린다.
  const finalComponents =
    step.type === "choice"
      ? (() => {
          const optionButtons = availableOptions(step, user).map((opt, i) =>
            button(opt.label, `choose:${user.stage}:${opt.value}`, (i % 4) + 1)
          );
          const freeButton = step.freeText ? button("✍️ 직접 입력", `free:${user.stage}`, 2) : null;
          if (!freeButton) return [row(...optionButtons)];
          return optionButtons.length < 5
            ? [row(...optionButtons, freeButton)]
            : [row(...optionButtons), row(freeButton)];
        })()
      : [row(button(step.actionLabel ?? "조사를 시작한다", `complete:${user.stage}`, 2))];

  return paged({
    embed: { title: step.title, footer: footerOf(step, user), color: 0x3498db },
    decor: step,
    body: text(step.description, user) + notes(user),
    page,
    full,
    kind: "s",
    stage: user.stage,
    finalComponents,
  });
}

