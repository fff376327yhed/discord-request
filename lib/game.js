// 관리자 페이지에서 "지금까지 유저들이 뭘 골랐는지"를 보여주기 위한 집계 함수.
// listUsers() 로 가져온 유저 배열을 그대로 넘기면 된다.

// 선택형(choice) 장면마다, 보기별로 몇 명이 그걸 골랐는지.
// user.choiceLog 는 지금 진행 중인(또는 마지막으로 끝낸) 회차 기준이라 다시 시작하면 비워진다 — 그래서 유저당 한 선택은 최대 한 번만 잡힌다.
export function computeChoiceStats(users) {
  const byStage = new Map(); // stage index -> { step, counts: Map(value -> n), total }
  for (const u of users) {
    for (const entry of u.choiceLog ?? []) {
      const step = STEPS[entry.stage];
      if (!step || step.type !== "choice") continue;
      if (!byStage.has(entry.stage)) byStage.set(entry.stage, { step, counts: new Map(), total: 0 });
      const bucket = byStage.get(entry.stage);
      bucket.counts.set(entry.value, (bucket.counts.get(entry.value) ?? 0) + 1);
      bucket.total += 1;
    }
  }
  return [...byStage.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([stage, bucket]) => ({
      stage,
      title: bucket.step.title,
      flagKey: bucket.step.flagKey ?? null,
      total: bucket.total,
      options: availableOptionsUnfiltered(bucket.step).map((o) => ({
        value: o.value,
        label: o.label,
        count: bucket.counts.get(o.value) ?? 0,
      })),
    }));
}

