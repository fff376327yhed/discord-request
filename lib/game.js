// ── 서술형(직접 입력) 선택 ──────────────────────────────
// 모달 입력창에서 받는 글의 최대 길이 (Discord 모달 자체 한도와 별개로 한 번 더 자른다)
export const FREE_TEXT_MAX_LEN = 200;

// 사용자가 직접 입력한 글을 step.freeText.rules 에 따라 기존 선택지 중 하나로 변환한다.
// 규칙은 위에서부터 먼저 걸리는 것을 쓰고, 아무 데도 안 걸리면 fallback 값의 옵션을 쓴다.
export function matchFreeText(step, rawText) {
  const rules = step.freeText?.rules ?? [];
  const lower = rawText.toLowerCase();
  const rule = rules.find((r) => r.keywords.some((kw) => lower.includes(kw.toLowerCase())));
  const value = rule?.value ?? step.freeText?.fallback;
  return (step.options ?? []).find((o) => o.value === value) ?? step.options[0];
}

// 선택(choice) 버튼을 눌렀을 때의 상태 변화 — interactions.js / admin.js 공용
export function applyChoice(user, step, option) {
  if (step.flagKey) {
    user.flags = user.flags ?? {};
    user.flags[step.flagKey] = option.value;
  }
  // 관리자 통계(computeChoiceStats)용 기록. advance() 가 stage 를 올리기 전에, "몇 번째 장면에서 뭘 골랐는지"를 남긴다.
  user.choiceLog = user.choiceLog ?? [];
  user.choiceLog.push({ stage: user.stage, value: option.value });
  addClues(user, text(option.gain, user));
  addAffinity(user, text(option.affinity, user));
  addHp(user, text(option.hp, user));
  advance(user, step);
}

